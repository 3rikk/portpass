// Run on a loaded site in a disposable browser profile.
async function checkBlocMap() {
  const assert=(value,message)=>{if(!value)throw Error(message);};
  const $=selector=>document.querySelector(selector), B=PortpassBlocMap;
  const visible=selector=>getComputedStyle($(selector)).display!=='none';
  assert($('#bloc-map-button').nextElementSibling.id==='advanced-button','Button directly above Advanced');
  assert($('#bloc-map-button').className===$('#advanced-button').className,'Matching button style');
  assert($('#bloc-view').hidden,'Personal map initially visible');
  assert(B.catalogue.length===24,'All supported bloc and agreement groups');
  assert(new Set(B.catalogue.map(b=>b.colour)).size===B.catalogue.length,'Every bloc has its own colour');
  docs=[{id:'test-passport',type:'passport',country:'DE'}];save();setMode('live');
  $('#search').value='France';$('#search').dispatchEvent(new Event('input'));
  $('#zoom-in').click();
  const personalFill=$('#world-map .country').getAttribute('fill');
  const wallet=JSON.stringify(docs), stored=localStorage.getItem('portpass-wallet-v1');
  const personalTransform=$('#world-map > g').getAttribute('transform');
  $('#bloc-map-button').click();
  assert(!$('#bloc-view').hidden && !visible('#personal-map-panel'),'Bloc map replaces personal map');
  for(const selector of ['.wallet','#stats','#visa-clocks','.destinations','.mode']) assert(!visible(selector),'Personal UI hidden: '+selector);
  assert($('#bloc-map-button').getAttribute('aria-expanded')==='true','Toggle state exposed');
  assert($('#bloc-key').children.length===B.catalogue.length,'Complete colour key');
  const france=$('#bloc-map [data-country=FR]');
  for (const target of [france,$('#bloc-map circle[data-country=JE]')]) {
    target.dispatchEvent(new MouseEvent('click',{bubbles:true}));
    assert($('#bloc-detail-dialog').open&&!$('#country-dialog').open,'Country click opens only bloc details');
    assert(document.querySelectorAll('dialog[open]').length===1,'No stacked personal popup');
    $('#bloc-detail-dialog [data-close]').click();
  }
  const fill=france.getAttribute('fill');
  assert(fill.startsWith('url(#bloc-overlap-'),'Overlapping membership patterned');
  const pattern=$(fill.slice(4,-1));
  const expected=B.memberships('FR');
  assert(pattern.querySelectorAll('rect').length===expected.length,'Pattern includes all overlapping colours');
  assert([...pattern.querySelectorAll('rect')].every((stripe,i)=>stripe.getAttribute('fill')===expected[i].colour&&Number(stripe.getAttribute('width'))>0),'Continuous coloured stripes');
  assert(france.getAttribute('stroke-dasharray')==='3 2','Overlap border is dashed');
  const pathFills=[...document.querySelectorAll('#bloc-map .country')].map(el=>el.getAttribute('fill'));
  docs=[];render();
  assert(JSON.stringify(pathFills)===JSON.stringify([...document.querySelectorAll('#bloc-map .country')].map(el=>el.getAttribute('fill'))),'Bloc map independent of wallet');
  docs=JSON.parse(wallet);render();
  for(const bloc of B.catalogue) for(const code of bloc.members) assert($(`#bloc-map [data-country="${code}"]`),'All members mapped: '+bloc.id+' '+code);
  assert($('#bloc-map circle[data-country=JE]')&&$('#bloc-map circle[data-country=FM]'),'Small places have markers');
  $('#bloc-key [data-bloc=eea]').click();
  assert(france.getAttribute('fill')===B.catalogue.find(b=>b.id==='eea').colour,'Selected bloc has solid colour');
  assert($('#bloc-map [data-country=US]').getAttribute('fill')==='var(--bloc-neutral)','Other blocs hidden while isolated');
  assert($('#bloc-selection').textContent.includes('Liechtenstein'),'Selected bloc conditions shown');
  $('#bloc-selection [data-member=LI]').click();
  assert($('#bloc-detail-dialog').open && $('#bloc-detail').textContent.includes('quotas'),'Member detail shows limits');
  $('#bloc-detail-dialog [data-close]').click();
  $('#bloc-key [data-bloc=apec]').click();
  assert($('#bloc-selection').textContent.includes('not settlement'),'Business initiative distinct from residence rights');
  $('#bloc-show-all').click();
  assert(france.getAttribute('fill')===fill,'All overlap colours restored');
  france.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));
  assert($('#bloc-detail-dialog').open,'Keyboard map navigation');
  assert(!$('#country-dialog').open,'Keyboard opens no personal popup');
  assert($('#bloc-detail').textContent.includes('EU / EEA')&&$('#bloc-detail').textContent.includes('Switzerland'),'Country lists all agreements');
  $('#bloc-detail-dialog [data-close]').click();
  $('#bloc-zoom-in').click();assert($('#bloc-map > g').getAttribute('transform').includes('scale(1.5)'),'Independent zoom');
  assert($('#world-map > g').getAttribute('transform')===personalTransform,'Personal zoom unchanged');
  $('#bloc-reset').click();assert($('#bloc-map > g').getAttribute('transform').includes('scale(1)'),'Bloc zoom reset');
  const theme=$('#theme-select').value;
  $('#theme-select').value='dark';$('#theme-select').dispatchEvent(new Event('change'));
  assert(getComputedStyle($('#bloc-view')).getPropertyValue('--bloc-neutral').trim()==='#303c49','Dark neutral palette');
  assert(france.getAttribute('fill')===fill,'Stable colours in dark mode');
  $('#theme-select').value=theme;$('#theme-select').dispatchEvent(new Event('change'));
  assert(document.documentElement.scrollWidth<=innerWidth,'No mobile horizontal overflow');
  $('#bloc-back').click();
  assert($('#bloc-view').hidden&&visible('#personal-map-panel')&&visible('.wallet'),'Return restores personal view');
  assert(mode==='live'&&query==='france'&&$('#search').value==='France','Personal mode and search preserved');
  assert(JSON.stringify(docs)===wallet&&localStorage.getItem('portpass-wallet-v1')===stored,'Wallet unchanged');
  assert($('#world-map .country').getAttribute('fill')===personalFill,'Personal colouring unchanged');
  $('#destination-list [data-country=FR]').click();
  assert($('#country-dialog').open&&!$('#bloc-detail-dialog').open,'Personal destination cards still open personal details');
  $('#country-dialog [data-close]').click();
  $('#bloc-map-button').click();$('#bloc-map-button').click();
  assert($('#bloc-view').hidden&&$('#bloc-map-button').getAttribute('aria-expanded')==='false','Button also returns to personal map');
  docs=[];save();render();$('#bloc-map-button').click();
  assert(!$('#bloc-view').hidden,'Blocs available without any wallet documents');
  return 'Bloc map passed: complete membership, dashed overlaps, key isolation, territories, wallet independence, keyboard, themes, zoom and return state.';
}
